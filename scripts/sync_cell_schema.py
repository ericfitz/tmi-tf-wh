"""Vendor the TMI diagram-cell schemas into tmi_tf/data/tmi_cell_schema.json.

Extracts Node, Edge and every schema they reference (transitively) from a TMI
OpenAPI document and converts the OpenAPI 3.0 dialect to JSON Schema:
`nullable: true` becomes a type union with "null", and OpenAPI-only keywords
(example, x-*, discriminator, ...) are dropped. `#/components/schemas/...` refs
keep their paths, so the output resolves them unchanged.

Usage (from a TMI checkout, pinned to a commit):
    git -C ~/Projects/tmi show origin/main:api-schema/tmi-openapi.json > /tmp/spec.json
    uv run python scripts/sync_cell_schema.py --spec /tmp/spec.json \
        --source "ericfitz/tmi@$(git -C ~/Projects/tmi rev-parse origin/main)"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOTS: tuple[str, ...] = ("Node", "Edge")
REF_PREFIX = "#/components/schemas/"
OPENAPI_ONLY = {"example", "examples", "discriminator", "xml", "externalDocs"}
DEFAULT_OUT = (
    Path(__file__).resolve().parent.parent / "tmi_tf/data/tmi_cell_schema.json"
)


class SchemaError(Exception):
    """The input spec cannot produce a cell schema."""


def _refs(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            if not ref.startswith(REF_PREFIX):
                raise SchemaError(f"unsupported $ref {ref!r}")
            found.add(ref[len(REF_PREFIX) :])
        for value in node.values():
            found |= _refs(value)
    elif isinstance(node, list):
        for value in node:
            found |= _refs(value)
    return found


def _convert(node: Any) -> Any:
    """OpenAPI 3.0 schema object -> JSON Schema (draft 2020-12 compatible)."""
    if isinstance(node, list):
        return [_convert(v) for v in node]
    if not isinstance(node, dict):
        return node
    out: dict[str, Any] = {}
    for key, value in node.items():
        if key in OPENAPI_ONLY or key.startswith("x-") or key == "nullable":
            continue
        if key == "properties" and isinstance(value, dict):
            out[key] = {name: _convert(sub) for name, sub in value.items()}
        else:
            out[key] = _convert(value)
    if node.get("nullable") is True:
        typ = out.get("type")
        if isinstance(typ, str):
            out["type"] = [typ, "null"]
        if "enum" in out and None not in out["enum"]:
            out["enum"] = [*out["enum"], None]
    return out


def extract(spec: dict[str, Any], source: str) -> dict[str, Any]:
    version = str(spec.get("openapi", ""))
    if not version.startswith("3.0."):
        raise SchemaError(f"expected an OpenAPI 3.0.x document, got {version!r}")
    schemas = spec.get("components", {}).get("schemas", {})
    missing = [r for r in ROOTS if r not in schemas]
    if missing:
        raise SchemaError(f"spec lacks schemas: {', '.join(missing)}")
    wanted: set[str] = set()
    todo: list[str] = list(ROOTS)
    while todo:
        name = todo.pop()
        if name in wanted:
            continue
        if name not in schemas:
            raise SchemaError(f"dangling reference to schema {name!r}")
        wanted.add(name)
        todo.extend(_refs(schemas[name]) - wanted)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": f"Generated by scripts/sync_cell_schema.py from {source} "
        f"(OpenAPI {version}). Do not edit by hand.",
        "components": {
            "schemas": {name: _convert(schemas[name]) for name in sorted(wanted)}
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--spec", required=True, type=Path, help="TMI OpenAPI JSON")
    parser.add_argument(
        "--source",
        required=True,
        help="provenance recorded in the output, e.g. ericfitz/tmi@<commit sha>",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        spec = json.loads(args.spec.read_text())
        result = extract(spec, args.source)
    except (OSError, json.JSONDecodeError, SchemaError) as e:
        print(f"sync_cell_schema: {e}", file=sys.stderr)
        return 1
    args.out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    count = len(result["components"]["schemas"])
    print(f"wrote {args.out} ({count} schemas)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
